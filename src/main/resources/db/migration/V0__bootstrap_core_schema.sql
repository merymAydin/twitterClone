-- Baseline schema for a completely empty database.
--
-- V1/V2 assume that the core tables already exist because this project originally relied on
-- Hibernate's ddl-auto=update to create them before Flyway ran. That is not reproducible.
-- This version-0 migration is applied from scratch on an empty schema; existing databases whose
-- baseline is version 1 ignore it and continue with V2+.

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    banner varchar(255),
    bio varchar(255),
    birthday timestamp(6) without time zone,
    email varchar(255),
    lan real,
    lon real,
    password varchar(255),
    photo varchar(255),
    user_name varchar(255),
    stripe_customer_id varchar(255)
);

CREATE TABLE IF NOT EXISTS public.tweets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    content varchar(255),
    lan real,
    lon real,
    parent_id bigint,
    user_id bigint,
    CONSTRAINT fk_tweets_user FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_tweets_parent FOREIGN KEY (parent_id) REFERENCES public.tweets(id)
);

CREATE TABLE IF NOT EXISTS public.comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    content varchar(255),
    tweet_id bigint,
    user_id bigint,
    CONSTRAINT fk_comments_tweet FOREIGN KEY (tweet_id) REFERENCES public.tweets(id),
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    tweet_id bigint,
    user_id bigint,
    CONSTRAINT ux_likes_tweet_user UNIQUE (tweet_id, user_id),
    CONSTRAINT fk_likes_tweet FOREIGN KEY (tweet_id) REFERENCES public.tweets(id),
    CONSTRAINT fk_likes_user FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.bookmarks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    tweet_id bigint,
    user_id bigint,
    CONSTRAINT ux_bookmarks_tweet_user UNIQUE (tweet_id, user_id),
    CONSTRAINT fk_bookmarks_tweet FOREIGN KEY (tweet_id) REFERENCES public.tweets(id),
    CONSTRAINT fk_bookmarks_user FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.follower (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    follower_id bigint,
    following_id bigint,
    CONSTRAINT fk_follower_user FOREIGN KEY (follower_id) REFERENCES public.users(id),
    CONSTRAINT fk_following_user FOREIGN KEY (following_id) REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    is_read boolean NOT NULL DEFAULT FALSE,
    message varchar(255),
    type varchar(255),
    recipient_id bigint,
    sender_id bigint,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES public.users(id),
    CONSTRAINT fk_notifications_sender FOREIGN KEY (sender_id) REFERENCES public.users(id),
    CONSTRAINT notifications_type_check CHECK (
        type IN ('FOLLOW', 'LIKE', 'COMMENT', 'MENTION')
    )
);

CREATE TABLE IF NOT EXISTS public.statistics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    created_by integer,
    is_deleted boolean NOT NULL DEFAULT FALSE,
    status integer,
    updated_at timestamp(6) without time zone,
    updated_by integer,
    bookmarks bigint DEFAULT 0,
    comments bigint DEFAULT 0,
    likes bigint DEFAULT 0,
    retweets bigint DEFAULT 0,
    views bigint DEFAULT 0,
    tweet_id bigint,
    quotes bigint NOT NULL DEFAULT 0,
    CONSTRAINT ux_statistics_tweet UNIQUE (tweet_id),
    CONSTRAINT fk_statistics_tweet FOREIGN KEY (tweet_id) REFERENCES public.tweets(id)
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);
CREATE INDEX IF NOT EXISTS idx_users_user_name ON public.users (user_name);
